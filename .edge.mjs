import { chromium } from '@playwright/test'
const scenario = process.argv[2]
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('[pageerror]', e.message))
await page.goto('http://localhost:5173/login?scenario=' + scenario)
await page.getByPlaceholder('contato@email.com').fill('ana@example.com')
await page.getByPlaceholder('Senha').fill('Senha@123')
await page.getByRole('button', { name: 'Entrar', exact: true }).click()
await page.waitForURL('http://localhost:5173/')
await page.goto('http://localhost:5173/nfts/nft-001')
await page.getByRole('button', { name: 'COMPRAR' }).click()
await page.waitForURL('**/cart')
await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
await page.waitForURL('**/checkout')
await page.getByLabel('Código de indicação').fill('AMIGO1')
await page.getByLabel('Nome ENS').fill('ana-coleciona')
await page.getByRole('button', { name: 'Conectar carteira' }).click()
await page.getByText('Conectada', { exact: true }).first().waitFor()
await page.getByRole('button', { name: 'Revisar pedido' }).click()
if (scenario === 'price-changed') {
  await page.getByText('Os valores mudaram desde a revisão').waitFor({ timeout: 10000 })
  console.log('stale banner shown')
  await page.getByRole('button', { name: /Confirmar compra/ }).click()
  await page.getByRole('dialog').waitFor()
  console.log('dialog:', (await page.getByRole('dialog').innerText()).replace(/\n/g, ' | '))
  await page.getByRole('button', { name: 'Aceitar novos valores' }).click()
  await page.getByRole('button', { name: /Confirmar compra/ }).click()
  await page.waitForURL('**/orders/**')
  console.log('order placed', page.url())
}
if (scenario === 'order-timeout') {
  await page.getByRole('button', { name: /Confirmar compra/ }).click()
  await page.getByText('Não recebemos a confirmação').waitFor({ timeout: 15000 })
  console.log('timeout message shown; orders:', await page.evaluate(() => window.__mock.snapshot().orders.length))
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await page.waitForURL('**/orders/**')
  console.log('recovered', page.url(), 'orders:', await page.evaluate(() => window.__mock.snapshot().orders.length))
}
await browser.close()
