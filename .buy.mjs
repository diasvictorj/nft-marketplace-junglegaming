import { chromium } from '@playwright/test'
const scenario = process.argv[2] ?? 'success'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('[pageerror]', e.message))
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 200)) })
await page.goto('http://localhost:5173/nfts/nft-001?scenario=' + scenario)
await page.getByRole('button', { name: 'COMPRAR' }).click()
await page.waitForURL('**/cart')
await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
await page.waitForURL('**/login**')
await page.getByPlaceholder('contato@email.com').fill('ana@example.com')
await page.getByPlaceholder('Senha').fill('Senha@123')
await page.getByRole('button', { name: 'Entrar', exact: true }).click()
await page.waitForURL('**/checkout')
await page.getByLabel('Código de indicação').fill('AMIGO1')
await page.getByLabel('Nome ENS').fill('ana-coleciona')
await page.getByRole('button', { name: 'Conectar carteira' }).click()
await page.getByText('Conectada', { exact: true }).first().waitFor()
await page.screenshot({ path: '/private/tmp/claude-501/-Users-joaovictordasilvadias-Desktop-Desenvolvimento-Desafios-tecnicos-Jungle-Gaming-Resources-nft-marketplace/a5cebf7e-d6ba-49c7-8e45-7321cc4ce389/scratchpad/checkout-d.png', fullPage: true })
await page.getByRole('button', { name: 'Revisar pedido' }).click()
await page.getByRole('heading', { name: 'Revise seu pedido' }).waitFor()
const confirmBtn = page.getByRole('button', { name: /Confirmar compra/ })
await confirmBtn.click()
await confirmBtn.click({ timeout: 500 }).catch(() => console.log('2nd click blocked'))
await page.waitForURL('**/orders/**', { timeout: 15000 })
console.log('order url', page.url())
await page.getByText(/Processando|Seus NFTs agora|recusado/).first().waitFor()
console.log('state1', (await page.locator('main').innerText()).slice(0, 60).replace(/\n/g, ' '))
await page.getByText(/Seus NFTs agora|Pagamento recusado/).waitFor({ timeout: 15000 })
console.log('state2', (await page.locator('main').innerText()).slice(0, 80).replace(/\n/g, ' '))
console.log('orders', await page.evaluate(() => window.__mock.snapshot().orders.length))
await page.screenshot({ path: '/private/tmp/claude-501/-Users-joaovictordasilvadias-Desktop-Desenvolvimento-Desafios-tecnicos-Jungle-Gaming-Resources-nft-marketplace/a5cebf7e-d6ba-49c7-8e45-7321cc4ce389/scratchpad/receipt-' + scenario + '.png', fullPage: true })
await browser.close()
